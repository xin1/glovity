#include "imu761_protocol.h"
#include <assert.h>
#include <string.h>

static const uint8_t sample[82] = {
    0x5A,0xA5,0x4C,0x00,0xD1,0x87,0x91,0x08,0x18,0x20,0x05,0x00,0x00,0x00,0xAB,0x49,
    0x00,0x00,0xB7,0x2B,0xFB,0x3B,0xBA,0x29,0xD0,0xBE,0x5A,0x5B,0x6A,0x3F,0xA6,0xC1,
    0x02,0xC0,0x57,0x67,0xE6,0x3D,0x7A,0xAD,0x11,0xBC,0x78,0x7E,0xB7,0xC1,0x0C,0xF9,
    0xD9,0xC1,0xCC,0x95,0x5B,0xC2,0x20,0xAB,0x1F,0xBF,0xC1,0xA6,0xBF,0xC1,0xC6,0x88,
    0x70,0xBF,0x8F,0x6A,0x7A,0x3F,0x19,0x8E,0x54,0xBE,0xFD,0x66,0x6D,0xBB,0x13,0xCF,
    0xE1,0xBB
};

int main(void) {
    imu761_parser_t parser = {0};
    imu761_data_t data;
    uint8_t query[5];
    imu761_build_query(1, query);
    assert(memcmp(query, "\x68\x04\x01\x03\x08", 5) == 0);
    imu761_build_query(2, query);
    assert(memcmp(query, "\x68\x04\x02\x03\x09", 5) == 0);
    assert(imu761_parser_feed(&parser, 0x00, &data) == 0);
    for (unsigned i = 0; i < sizeof sample; ++i)
        assert(imu761_parser_feed(&parser, sample[i], &data) == (i == sizeof sample - 1));
    assert(data.address == 5);
    assert(data.timestamp_ms == 0x49AB);
    assert(parser.crc_errors == 0);
    uint8_t bad[82];
    memcpy(bad, sample, sizeof bad);
    bad[20] ^= 1;
    for (unsigned i = 0; i < sizeof bad; ++i)
        assert(imu761_parser_feed(&parser, bad[i], &data) == 0);
    assert(parser.crc_errors == 1);
    return 0;
}
